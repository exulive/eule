using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Design;
using Microsoft.EntityFrameworkCore.Storage.ValueConversion;

namespace Eule.Server.Data;

public sealed class User
{
    public Guid Id { get; set; } = Guid.NewGuid();
    /// <summary>Stored lower-case; unique.</summary>
    public string Email { get; set; } = "";
    public string DisplayName { get; set; } = "";
    public string PasswordHash { get; set; } = "";
    public bool IsActive { get; set; } = true;
    public DateTime CreatedAt { get; set; }
    public DateTime? LastLoginAt { get; set; }
}

/// <summary>Long-lived sign-in. Only a SHA-256 hash of the token is stored; tokens rotate on every use.</summary>
public sealed class RefreshToken
{
    public Guid Id { get; set; } = Guid.NewGuid();
    public Guid UserId { get; set; }
    public string TokenHash { get; set; } = "";
    public string? Device { get; set; }
    public DateTime CreatedAt { get; set; }
    public DateTime ExpiresAt { get; set; }
    public DateTime? RevokedAt { get; set; }
    public Guid? ReplacedById { get; set; }
}

public sealed class Note
{
    public Guid Id { get; set; } = Guid.NewGuid();
    public Guid UserId { get; set; }
    /// <summary>What was said or typed, unchanged.</summary>
    public string Text { get; set; } = "";
    public string Title { get; set; } = "";
    public DateTime? DueAt { get; set; }
    /// <summary>False when only a day was given.</summary>
    public bool HasTime { get; set; }
    /// <summary>IANA zone the time was understood in, e.g. Europe/Istanbul.</summary>
    public string TimeZone { get; set; } = "";
    public bool Done { get; set; }
    /// <summary>"voice" or "text".</summary>
    public string Source { get; set; } = "voice";
    public DateTime CreatedAt { get; set; }
    public DateTime UpdatedAt { get; set; }
    /// <summary>Soft delete, so other devices can learn about it when they sync.</summary>
    public DateTime? DeletedAt { get; set; }
}

/// <summary>Every dictation and what the agent did with it: the audit trail for future AI actions.</summary>
public sealed class Dictation
{
    public Guid Id { get; set; } = Guid.NewGuid();
    public Guid UserId { get; set; }
    /// <summary>Generated by the client; makes retries safe (same id = same result, no duplicate note).</summary>
    public Guid ClientId { get; set; }
    public string Text { get; set; } = "";
    public string TimeZone { get; set; } = "";
    public string Source { get; set; } = "voice";
    public DateTime ReceivedAt { get; set; }
    public string Agent { get; set; } = "";
    public string Action { get; set; } = "";
    public Guid? NoteId { get; set; }
    public string Reply { get; set; } = "";
}

public sealed class EuleDbContext(DbContextOptions<EuleDbContext> options) : DbContext(options)
{
    public DbSet<User> Users => Set<User>();
    public DbSet<RefreshToken> RefreshTokens => Set<RefreshToken>();
    public DbSet<Note> Notes => Set<Note>();
    public DbSet<Dictation> Dictations => Set<Dictation>();

    protected override void OnModelCreating(ModelBuilder b)
    {
        b.Entity<User>(e =>
        {
            e.ToTable("users");
            e.HasIndex(x => x.Email).IsUnique();
            e.Property(x => x.Email).HasMaxLength(256);
            e.Property(x => x.DisplayName).HasMaxLength(100);
            e.Property(x => x.PasswordHash).HasMaxLength(512);
        });
        b.Entity<RefreshToken>(e =>
        {
            e.ToTable("refresh_tokens");
            e.HasIndex(x => x.TokenHash).IsUnique();
            e.HasIndex(x => x.UserId);
            e.Property(x => x.TokenHash).HasMaxLength(64);
            e.Property(x => x.Device).HasMaxLength(200);
        });
        b.Entity<Note>(e =>
        {
            e.ToTable("notes");
            e.HasIndex(x => new { x.UserId, x.UpdatedAt });
            e.Property(x => x.Text).HasMaxLength(2000);
            e.Property(x => x.Title).HasMaxLength(500);
            e.Property(x => x.TimeZone).HasMaxLength(64);
            e.Property(x => x.Source).HasMaxLength(16);
        });
        b.Entity<Dictation>(e =>
        {
            e.ToTable("dictations");
            e.HasIndex(x => new { x.UserId, x.ClientId }).IsUnique();
            e.Property(x => x.Text).HasMaxLength(2000);
            e.Property(x => x.TimeZone).HasMaxLength(64);
            e.Property(x => x.Source).HasMaxLength(16);
            e.Property(x => x.Agent).HasMaxLength(64);
            e.Property(x => x.Action).HasMaxLength(64);
            e.Property(x => x.Reply).HasMaxLength(1000);
        });

        // Every timestamp is UTC. Postgres keeps it (timestamptz); SQLite (tests) loses the kind, so set it back on read.
        var utc = new ValueConverter<DateTime, DateTime>(v => v, v => DateTime.SpecifyKind(v, DateTimeKind.Utc));
        var utcNullable = new ValueConverter<DateTime?, DateTime?>(
            v => v, v => v.HasValue ? DateTime.SpecifyKind(v.Value, DateTimeKind.Utc) : v);
        foreach (var entity in b.Model.GetEntityTypes())
            foreach (var p in entity.GetProperties())
            {
                if (p.ClrType == typeof(DateTime)) p.SetValueConverter(utc);
                else if (p.ClrType == typeof(DateTime?)) p.SetValueConverter(utcNullable);
            }
    }
}

/// <summary>Lets <c>dotnet ef migrations add</c> build the PostgreSQL model without starting the web app.</summary>
public sealed class DesignTimeFactory : IDesignTimeDbContextFactory<EuleDbContext>
{
    public EuleDbContext CreateDbContext(string[] args) =>
        new(new DbContextOptionsBuilder<EuleDbContext>()
            .UseNpgsql("Host=localhost;Database=eule;Username=eule;Password=design-time-only")
            .Options);
}
